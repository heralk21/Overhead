def layout(text):
    on, off = [], []
    cx = 0
    for ch in text.upper():
        g = F.get(ch, F[" "])
        for r in range(7):
            for c in range(5):
                if g[r][c] == "1": on.append((cx + c, r))
                elif ch != " ": off.append((cx + c, r))
        cx += 6
    cols = cx - 1 if text else 0
    return cols, on, off

def render(text, pitch=8, color=(115, 184, 235), off=True, pad=None):
    """Return a tight RGBA image of the LED text with baked glow."""
    if pad is None: pad = int(pitch * 1.6)
    cols, ons, offs = layout(text)
    W = cols * pitch + pad * 2
    Hh = 7 * pitch + pad * 2
    core = Image.new("RGBA", (W, Hh), (0, 0, 0, 0))
    d = ImageDraw.Draw(core)
    r = pitch * 0.42
    def dot(cx, cy, rad, col, a):
        d.ellipse([cx-rad, cy-rad, cx+rad, cy+rad], fill=(col[0], col[1], col[2], a))
    if off:
        for (c, rr) in offs:
            x = pad + c*pitch + pitch/2; y = pad + rr*pitch + pitch/2
            dot(x, y, r*0.8, color, 26)          # ~10% dim off-pixels
    for (c, rr) in ons:
        x = pad + c*pitch + pitch/2; y = pad + rr*pitch + pitch/2
        dot(x, y, r, color, 255)
        dot(x, y, r*0.42, (255, 255, 255), 200)  # hot center
    glow = core.filter(ImageFilter.GaussianBlur(pitch*0.55))
    out = Image.new("RGBA", (W, Hh), (0, 0, 0, 0))
    out = Image.alpha_composite(out, glow)
    out = Image.alpha_composite(out, glow)       # double for bloom
    out = Image.alpha_composite(out, core)
    return out
